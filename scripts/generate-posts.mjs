import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.join(process.cwd(), 'app', 'blog', 'posts');
const files = readdirSync(dir).filter((f) => f.endsWith('.md'));
const posts = Object.fromEntries(
  files.map((f) => [f, readFileSync(path.join(dir, f), 'utf8')]),
);

writeFileSync(
  path.join(process.cwd(), 'app', 'blog', 'posts.generated.ts'),
  `// Generated by scripts/generate-posts.mjs. Do not edit.\nexport const rawPosts: Record<string, string> = ${JSON.stringify(posts, null, 2)};\n`,
);
